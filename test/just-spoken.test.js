test('where cues overlap in time, H can take each line: pressed 1.2 s after a line starts, it takes that line', async () => {
  // "Fine." comes on at 11 s, while the cue before it stays up until 14 s. Two more cues come on together at 14 s.
  const open = await panelOn(talk, cues([10, 14, 'Good morning. How are you?'], [11, 13, 'Fine.'], [14, 16, 'And you?'], [14, 16, 'Very well.'], [16, 18, 'Good.']));
  const { sentences } = open.now().transcript;
  assert.deepEqual(sentences.map((sentence) => sentence.text), ['Good morning.', 'How are you?', 'Fine.', 'And you?', 'Very well.', 'Good.']);

  for (const sentence of sentences) {
    open.clock.pass(60); // long after the Highlight before it was made, so that H takes a sentence afresh
    await pressHAt(open, sentence.start + 1.2);
  }

  assert.deepEqual(wordsOf(open.now()), ['Good morning.', 'How are you?', 'Fine.', 'And you?', 'Very well.', 'Good.']);
  assert.deepEqual(lines(open.now()), ['«Good morning.»', '«How are you?»', '«Fine.»', '«And you?»', '«Very well.»', '«Good.»']);
});

