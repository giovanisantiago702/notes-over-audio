// H keeps the sentence just spoken: which sentence that is, the Highlight it
// makes, and how H again reaches one sentence further back. The rule is the
// prototype's, but for one thing since ticket 23: H grows only a Highlight that H made,
// where the prototype's H grew one made by selecting as well.

import assert from 'node:assert/strict';

import { colourOf } from '../src/core/highlights.js';
import { reachBack, sentenceJustSpoken } from '../src/core/just-spoken.js';
import { cutIntoSentences } from '../src/core/transcript.js';
import { dinner, lines, marked, morning, panelOn, pressHAt, saying, select, settled, talk, wordsOf } from './open-panel.js';
import { fromTheUploader, oldAutoGenerated, recentAutoGenerated, test } from './real-captions.js';

const sentencesOf = (transcript) => cutIntoSentences(transcript).sentences;
/** The sentence H takes at a time, as its text, or null when it takes none. */
const taken = (transcript, seconds) => {
  const sentences = sentencesOf(transcript);
  return sentences[sentenceJustSpoken(sentences, seconds)]?.text ?? null;
};

test('H takes the sentence that was being said 1.2 s earlier', () => {
  // "Good morning." from 10 s, "How are you?" from 12 s, "Fine." from 20 s.
  const greeting = saying([10, 'Good morning.'], [12, 'How are you?'], [20, 'Fine.']);

  // At 13 s "How are you?" is being said, and 1.2 s earlier "Good morning." still was.
  assert.equal(taken(greeting, 13), 'Good morning.');
  assert.equal(taken(greeting, 13.2), 'How are you?');
  // A sentence stays the one through the silence after it.
  assert.equal(taken(greeting, 21.1), 'How are you?');
  assert.equal(taken(greeting, 21.2), 'Fine.');
});

test('H skips a bracketed sound, back to what was last said', () => {
  const applause = saying([10, 'Thank you.'], [12, '[applause]'], [14, '[Music]'], [20, 'Please remain seated.']);

  // 1.2 s before 13.5 s and before 16 s there was only applause and music.
  assert.equal(taken(applause, 13.5), 'Thank you.');
  assert.equal(taken(applause, 16), 'Thank you.');
  assert.equal(taken(applause, 21.2), 'Please remain seated.');
});

test('H takes nothing before anything has been said', () => {
  const opening = saying([2, '[Music]'], [10, 'Good morning.']);

  assert.equal(taken(opening, 0), null);
  assert.equal(taken(opening, 1), null);
  // Music is not something said, and 1.2 s before 11.1 s nothing else had been.
  assert.equal(taken(opening, 5), null);
  assert.equal(taken(opening, 11.1), null);
  assert.equal(taken(opening, 11.2), 'Good morning.');
});

test('on the real captions H takes the sentence that was being said 1.2 s earlier, word-timed or cue-timed', () => {
  // Auto-generated in 2026, a time for every word: "Please remain seated." from 4 s, "That's not necessary." from 5.16 s.
  assert.equal(taken(recentAutoGenerated(), 6.3), 'Please remain seated.');
  assert.equal(taken(recentAutoGenerated(), 6.4), "That's not necessary.");
  // The first line is [applause], from 0.654 s, and "Thank you." comes at 0.8 s.
  assert.equal(taken(recentAutoGenerated(), 1.9), null);
  assert.equal(taken(recentAutoGenerated(), 2), 'Thank you.');

  // The uploader's captions, timed per cue: "In fact, I'm leaving." from 35.753 s, (Laughter) from 37.269 s
  // until "There have been three themes…" at 43.096 s. H during the laughter takes what was said before it.
  assert.equal(taken(fromTheUploader(), 38), "In fact, I'm leaving.");
  assert.equal(taken(fromTheUploader(), 44.2), "In fact, I'm leaving.");
  assert.match(taken(fromTheUploader(), 44.3), /^There have been three themes/);

  // Auto-generated in 2007, with no punctuation: [Music] from 6.26 s, "good morning" from 26.56 s, "how are you" from 28.4 s.
  assert.equal(taken(oldAutoGenerated(), 20), null);
  assert.equal(taken(oldAutoGenerated(), 29.5), 'good morning');
  assert.equal(taken(oldAutoGenerated(), 29.6), 'how are you');
});

