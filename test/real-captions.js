// The three real sets of captions, as Transcripts. They were fetched from
// YouTube on 2026-10-07, and are the size the live check saw in the tab to the
// character. Tests of the core read them through here, so the core's tests
// never see YouTube's format.
//
// The captions themselves are not kept in the repository: they are the words
// of two videos, and their makers'. They go in test/captions/, which git
// ignores, under the names below. Where one is not there, a test that asks for
// it is skipped, not failed. So a file whose tests read them takes its `test`
// from here.

import { existsSync, readFileSync } from 'node:fs';
import { test as plainTest } from 'node:test';

import { transcriptFromCaptions } from '../src/extension/youtube-captions.js';

const kept = new URL('./captions/', import.meta.url);

/** What the test now running asked for and did not find, or null. */
let notHere = null;

const read = (file, track) => {
  const from = new URL(file, kept);
  if (!existsSync(from)) {
    notHere = `test/captions/${file} is not here`;
    throw new Error(notHere);
  }
  return transcriptFromCaptions(readFileSync(from, 'utf8'), track);
};

/**
 * `test`, for a file whose tests read the real captions. A test that fails
 * after asking for a set that is not here is skipped: whatever stood between
 * the asking and the failing, the panel's own handling of a failed fetch say,
 * it could not have passed. The tests of a file run one at a time, so what was
 * asked for is the running test's.
 */
export const test = (name, run) =>
  plainTest(name, async (context) => {
    notHere = null;
    try {
      await run();
    } catch (error) {
      if (!notHere) throw error;
      context.skip(notHere);
    }
  });

/** Auto-generated in 2026: punctuated, timed per word, speakers marked. 27 minutes. */
export const recentAutoGenerated = () => read('rddfPNBNAJs.auto.en.json3', { language: 'en', auto: true });

/** The uploader's captions of a 2007 talk: punctuated, timed per cue. 20 minutes. */
export const fromTheUploader = () => read('iG9CE55wbtY.manual.en.json3', { language: 'en', auto: false });

/** Auto-generated captions of the same talk: no punctuation, timed per word. */
export const oldAutoGenerated = () => read('iG9CE55wbtY.auto.en.json3', { language: 'en', auto: true });
